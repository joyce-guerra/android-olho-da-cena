'use strict';
const { _electron } = require('playwright');
const fs = require('fs'), path = require('path'), os = require('os');
const RAIZ = process.argv[2], MIDIA = process.argv[3];
const espera = (ms) => new Promise((r) => setTimeout(r, ms));
let falhas = 0;
const ok = (n, c, x = '') => { console.log(`${c ? 'ok    ' : 'FALHOU'} ${n}${x !== '' ? ' — ' + String(x).slice(0, 300) : ''}`); if (!c) falhas++; };
(async () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'olho-as-'));
  const pasta = path.join(tmp, 'meus'); fs.mkdirSync(pasta);
  for (const f of ['fala.mp3', 'clipe.mp4']) fs.copyFileSync(path.join(MIDIA, f), path.join(pasta, f));
  const app = await _electron.launch({ executablePath: require(path.join(RAIZ, 'node_modules', 'electron')), args: ['--no-sandbox', RAIZ], cwd: RAIZ,
    env: { ...process.env, OLHO_TESTE_DADOS: path.join(tmp, 'dados'), OLHO_TESTE_DOCUMENTOS: path.join(tmp, 'Documentos') } });
  const w = await app.firstWindow();
  const erros = []; w.on('pageerror', (e) => erros.push(e.message));
  await app.evaluate(({ dialog }) => { global.__abrir = []; dialog.showOpenDialog = async () => { const p = global.__abrir.shift(); return p ? { canceled: false, filePaths: [].concat(p) } : { canceled: true, filePaths: [] }; }; });
  const abrir = (p) => app.evaluate((_e, x) => { global.__abrir.push(x); }, p);
  const ate = async (f, arg, ms = 30000) => { const t0 = Date.now(); while (Date.now() - t0 < ms) { if (await w.evaluate(f, arg)) return true; await espera(150); } return false; };
  const status = () => w.evaluate(() => document.getElementById('status').textContent);
  const clicar = async (id) => { await ate((i) => { const e = document.getElementById(i); return e && !e.disabled && e.offsetParent !== null; }, id); await w.click('#' + id); };
  await ate(() => window.gravarTela && window.olho); await espera(1000);
  await w.keyboard.press('Alt+KeyS');
  ok('tela inicial: nada para salvar', await ate(() => /Nada para salvar nesta tela/.test(document.getElementById('status').textContent), null, 3000), await status());
  await clicar('ir-cortar');
  await w.keyboard.press('Alt+KeyS');
  ok('Edição sem arquivo: avisa', await ate(() => /Adicione um vídeo ou um áudio/.test(document.getElementById('status').textContent), null, 3000), await status());
  await abrir(path.join(pasta, 'clipe.mp4')); await clicar('ed-adicionar'); await ate(() => /clipe/.test(document.getElementById('ed-info').textContent));
  await w.keyboard.press('Alt+KeyS');
  ok('Edição: Alt S salva em vídeo e em áudio', await ate(() => /^Salvo em vídeo e em áudio, na pasta .* com o nome clipe - salvo\.?$/.test(document.getElementById('status').textContent.trim()), null, 60000), await status());
  const pv = path.join(tmp, 'Documentos', 'Olho da Cena');
  ok('arquivos salvos', fs.existsSync(path.join(pv, 'clipe - salvo.mp4')) && fs.existsSync(path.join(pv, 'clipe - salvo.mp3')), fs.existsSync(pv) ? fs.readdirSync(pv).join(', ') : '');
  await w.keyboard.press('Alt+KeyV');
  ok('Alt V na Edição volta ao início', await ate(() => window.olho.telaAtual() === 'inicial', null, 5000));
  await clicar('ir-gravar'); await espera(1500);
  await w.keyboard.press('Alt+KeyS');
  ok('Gravar antes de gravar: nada para salvar', await ate(() => /Nada para salvar ainda\. Grave primeiro/.test(document.getElementById('status').textContent), null, 3000), await status());
  await w.keyboard.press('Alt+KeyV');
  ok('Alt V na Etapa 1 do Gravar volta ao início', await ate(() => window.olho.telaAtual() === 'inicial', null, 5000));
  await clicar('ir-gerar');
  await w.keyboard.press('Alt+KeyS');
  ok('Montar antes do áudio: nada para salvar', await ate(() => /Nada para salvar ainda\. O áudio fica pronto/.test(document.getElementById('status').textContent), null, 3000), await status());
  await w.keyboard.press('Alt+KeyV');
  await clicar('ir-config'); await espera(300);
  await w.keyboard.press('Alt+KeyV');
  ok('Alt V nas Configurações volta ao início', await ate(() => window.olho.telaAtual() === 'inicial', null, 5000));
  ok('sem erros na página', erros.length === 0, erros.join(' | '));
  await app.close();
  console.log(falhas ? `${falhas} falha(s)` : 'tudo certo'); process.exit(falhas ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(2); });
