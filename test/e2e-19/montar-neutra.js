'use strict';
const { _electron } = require('playwright');
const fs = require('fs'), path = require('path'), os = require('os');
const { execFileSync } = require('child_process');
const RAIZ = process.argv[2], MIDIA = process.argv[3];
const espera = (ms) => new Promise((r) => setTimeout(r, ms));
let falhas = 0;
const ok = (n, c, x = '') => { console.log(`${c ? 'ok    ' : 'FALHOU'} ${n}${x !== '' ? ' — ' + String(x).slice(0, 300) : ''}`); if (!c) falhas++; };
const sonda = (a) => execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration:stream=codec_type', '-of', 'json', a]).toString();
(async () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'olho-mo-'));
  const pasta = path.join(tmp, 'meus'); fs.mkdirSync(pasta);
  for (const f of ['neutra.wav', 'img1.png', 'img2.png']) fs.copyFileSync(path.join(MIDIA, f), path.join(pasta, f));
  const saida = path.join(tmp, 'saida.mp4');
  const app = await _electron.launch({ executablePath: require(path.join(RAIZ, 'node_modules', 'electron')), args: ['--no-sandbox', RAIZ], cwd: RAIZ,
    env: { ...process.env, OLHO_TESTE_DADOS: path.join(tmp, 'dados'), OLHO_TESTE_DOCUMENTOS: path.join(tmp, 'Documentos') } });
  const w = await app.firstWindow();
  const erros = [];
  w.on('pageerror', (e) => erros.push(e.message + ' @ ' + (e.stack || '').split('\n').slice(1, 3).join(' ')));
  w.on('console', (m) => { if (m.type() === 'error' && !/Autofill|DevTools|XNNPACK/.test(m.text())) erros.push('console: ' + m.text()); });
  await app.evaluate(({ dialog }, s) => {
    global.__abrir = [];
    dialog.showOpenDialog = async () => { const p = global.__abrir.shift(); return p ? { canceled: false, filePaths: [].concat(p) } : { canceled: true, filePaths: [] }; };
    dialog.showSaveDialog = async () => ({ canceled: false, filePath: s });
  }, saida);
  const abrir = (p) => app.evaluate((_e, x) => { global.__abrir.push(x); }, p);
  const ate = async (f, arg, ms = 60000) => { const t0 = Date.now(); while (Date.now() - t0 < ms) { if (await w.evaluate(f, arg)) return true; await espera(150); } return false; };
  const tela = () => w.evaluate(() => window.olho.telaAtual());
  const etapa = () => w.evaluate(() => [1, 2, 3, 4, 5, 6, 7, 8].find((i) => !document.getElementById('g-etapa-' + i).hidden));
  const status = () => w.evaluate(() => document.getElementById('status').textContent);
  const clicar = async (id) => { await ate((i) => { const e = document.getElementById(i); return e && !e.disabled && e.offsetParent !== null; }, id); await w.click('#' + id); };
  await ate(() => window.gravarTela && window.olho);
  await espera(1200);

  await clicar('ir-gerar');
  ok('Montar abre na Etapa 1 de 8', (await tela()) === 'gerar' && (await etapa()) === 1 && (await w.textContent('#g-etapa-1-titulo')) === 'Etapa 1 de 8: Áudio');
  ok('oito etapas na navegação', await w.evaluate(() => document.querySelectorAll('#g-etapas button').length === 8));
  ok('sem silêncios nem trilhas antigas', await w.evaluate(() => !document.getElementById('btn-detectar-silencio') && !document.getElementById('g-btn-add-trilha')));
  ok('botões da Etapa 1', await w.evaluate(() => ['g-continuar-1', 'g-voltar-1', 'g-fechar-1'].map((i) => document.getElementById(i).textContent).join('|')) === 'Salvar e continuar, Alt A|Voltar, Alt V|Fechar');
  await clicar('g-nav-3');
  ok('antes do áudio, não pula para a Etapa 3', (await etapa()) === 1 && /Primeiro o áudio/.test(await status()), await status());
  await abrir(path.join(pasta, 'neutra.wav'));
  await clicar('btn-audio');
  await ate(() => window.__olhoEstado ? true : /fala/.test(document.getElementById('info-audio').textContent));
  await w.keyboard.press('Alt+KeyA');
  ok('Alt A leva para as etapas de áudio, Cortes', await ate(() => window.olho.telaAtual() === 'audio' && /Áudio fala/.test(document.getElementById('au-info').textContent) && !document.getElementById('au-cortes').hidden), await w.textContent('#au-info'));
  await ate(() => document.getElementById('au-player').readyState >= 1);
  await w.evaluate(() => { document.getElementById('au-player').currentTime = 1; });
  await ate(() => Math.abs(document.getElementById('au-player').currentTime - 1) < 0.05);
  await clicar('au-inicio');
  await w.evaluate(() => { document.getElementById('au-player').currentTime = 3; });
  await ate(() => Math.abs(document.getElementById('au-player').currentTime - 3) < 0.05);
  await clicar('au-fim');
  await clicar('au-descartar');
  await clicar('au-continuar'); await ate(() => !document.getElementById('au-silencios').hidden);
  await clicar('aus-continuar'); await ate(() => !document.getElementById('au-trilhas').hidden);
  await clicar('aut-continuar'); await ate(() => !document.getElementById('au-eq').hidden);
  await clicar('aue-continuar');
  ok('depois da Equalização, volta para o Montar, Etapa 2', await ate(() => window.olho.telaAtual() === 'gerar' && !document.getElementById('g-etapa-2').hidden, null, 120000));
  ok('a pasta do usuário não ganhou arquivos', fs.readdirSync(pasta).sort().join() === 'neutra.wav,img1.png,img2.png', fs.readdirSync(pasta).join());
  await w.keyboard.press('Alt+KeyV');
  ok('Voltar da Etapa 2 volta para Equalização e ajustes', await ate(() => window.olho.telaAtual() === 'audio' && !document.getElementById('au-eq').hidden, null, 10000));
  await clicar('aue-continuar');
  await ate(() => window.olho.telaAtual() === 'gerar' && !document.getElementById('g-etapa-2').hidden, null, 120000);
  await clicar('g-continuar-2');
  ok('Etapa 3: Imagens', (await etapa()) === 3);
  await clicar('g-continuar-3');
  ok('sem imagens, não avança', (await etapa()) === 3 && /Adicione pelo menos uma imagem/.test(await status()), await status());
  await abrir([path.join(pasta, 'img1.png'), path.join(pasta, 'img2.png')]);
  await clicar('btn-imagens');
  await ate(() => /2/.test(document.getElementById('info-imagens').textContent));
  await clicar('g-continuar-3');
  ok('depois das Imagens, a tela de legenda', await ate(() => window.olho.telaAtual() === 'legenda', null, 10000));
  await w.keyboard.press('Alt+KeyA');
  ok('Alt A na legenda segue sem legenda, para a Etapa 5', await ate(() => window.olho.telaAtual() === 'gerar' && !document.getElementById('g-etapa-5').hidden, null, 10000));
  for (const n of [5, 6, 7]) { await clicar('g-continuar-' + n); }
  ok('chega na Etapa 8: Atmosfera e qualidade', (await etapa()) === 8 && (await w.textContent('#g-etapa-8-titulo')) === 'Etapa 8 de 8: Atmosfera e qualidade');
  ok('Etapa 8 sem Salvar e continuar e sem o Voltar ao início antigo', await w.evaluate(() => !document.getElementById('g-continuar-8') && !document.getElementById('btn-voltar')));
  await w.keyboard.press('Control+5');
  ok('Ctrl 5 vai para a Etapa 5', (await etapa()) === 5);
  await w.keyboard.press('Control+8');
  await clicar('btn-gerar');
  ok('vídeo montado', await ate(() => !document.getElementById('btn-abrir').hidden, null, 300000), await status());
  if (fs.existsSync(saida)) {
    const j = JSON.parse(sonda(saida));
    const d = Number(j.format.duration);
    ok('vídeo com imagem e som, com o corte de 2 segundos', Math.abs(d - 8) < 0.5 && j.streams.some((x) => x.codec_type === 'audio') && j.streams.some((x) => x.codec_type === 'video'), d);
  } else ok('arquivo do vídeo existe', false, saida);
  ok('sem erros na página', erros.length === 0, erros.join(' | '));
  await app.close();
  console.log(falhas ? `${falhas} falha(s)` : 'tudo certo');
  process.exit(falhas ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(2); });
