'use strict';
const { _electron } = require('playwright');
const fs = require('fs'), path = require('path'), os = require('os');
const RAIZ = process.argv[2], MIDIA = '/tmp/gravador-teste-midia';
const espera = (ms) => new Promise((r) => setTimeout(r, ms));
let falhas = 0;
const ok = (n, c, x = '') => { console.log(`${c ? 'ok    ' : 'FALHOU'} ${n}${x !== '' ? ' — ' + String(x).slice(0, 300) : ''}`); if (!c) falhas++; };
(async () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'olho-gr-'));
  const app = await _electron.launch({ executablePath: require(path.join(RAIZ, 'node_modules', 'electron')), args: ['--no-sandbox', RAIZ], cwd: RAIZ,
    env: { ...process.env, OLHO_TESTE_DADOS: path.join(tmp, 'dados'), OLHO_TESTE_DOCUMENTOS: path.join(tmp, 'Documentos'),
      OLHO_TESTE_VIDEO: path.join(MIDIA, 'centrado.y4m'), OLHO_TESTE_MIC: path.join(MIDIA, 'mic.wav') } });
  const w = await app.firstWindow();
  const erros = [];
  w.on('pageerror', (e) => erros.push(e.message + ' @ ' + (e.stack || '').split('\n').slice(1, 3).join(' ')));
  const ate = async (f, arg, ms = 30000) => { const t0 = Date.now(); while (Date.now() - t0 < ms) { if (await w.evaluate(f, arg)) return true; await espera(150); } return false; };
  const visivel = (id) => w.evaluate((i) => { const e = document.getElementById(i); return !!e && e.offsetParent !== null; }, id);
  const etapa = () => w.evaluate(() => [1, 2, 3, 4].find((i) => !document.getElementById('grav-e' + i).hidden));
  const ultima = () => w.evaluate(() => window.__gravador.anuncios.slice(-1)[0] || '');
  const foco = () => w.evaluate(() => document.activeElement && document.activeElement.id);
  await ate(() => window.gravarTela && window.olho);
  await espera(1200);

  await w.evaluate(() => document.getElementById('ir-gravar').click());
  await ate(() => window.olho.telaAtual() === 'gravar');
  await ate(() => window.gravarTela.estado.pronto, null, 30000);
  ok('abre na Etapa 1', (await etapa()) === 1);
  ok('Etapa 1 só mostra proporção, qualidade e os três botões', (await visivel('grupo-formato')) && (await visivel('grupo-qualidade')) && !(await visivel('camera')) && !(await visivel('texto')) && !(await visivel('gravar')));
  ok('fala da entrada', /Etapa 1 de 4: Proporção e qualidade/.test(await w.evaluate(() => window.__gravador.anuncios.join(' | '))), await w.evaluate(() => window.__gravador.anuncios.slice(-3).join(' | ')));
  ok('botões com Alt A e Alt V', (await w.textContent('#grav-e1-continuar')) === 'Salvar e continuar, Alt A' && (await w.textContent('#grav-e1-voltar')) === 'Voltar, Alt V');
  await w.keyboard.press('Alt+KeyR');
  await espera(300);
  ok('Alt R na Etapa 1 explica onde grava', /Alt R grava na Etapa 4/.test(await ultima()), await ultima());
  ok('Alt R na Etapa 1 não grava', await w.evaluate(() => !window.__gravador.gravador || window.__gravador.gravador.state === 'inactive'));
  await w.keyboard.press('Alt+KeyA');
  await espera(400);
  ok('sem proporção, Alt A não avança e foca a escolha', (await etapa()) === 1 && /escolha a proporção/i.test(await w.textContent('#alerta')), await w.textContent('#alerta'));
  await w.check('input[name="formato"][value="horizontal"]');
  await w.evaluate(() => { const r = document.querySelector('input[name="qualidade"]'); r.click(); });
  await w.keyboard.press('Alt+KeyA');
  await espera(400);
  ok('Alt A vai para a Etapa 2', (await etapa()) === 2 && (await foco()) === 'grav-e2-titulo', await foco());
  ok('Etapa 2: câmera e microfone à vista', (await visivel('camera')) && (await visivel('microfone')) && (await visivel('espelhada')) && !(await visivel('grupo-formato')));
  await w.keyboard.press('Alt+KeyE');
  ok('Alt E funciona na Etapa 2', await ate(() => /rosto|enquadr|Ninguém|corpo/i.test(window.__gravador.anuncios.slice(-1)[0] || ''), null, 60000), await ultima());
  await w.click('#grav-e2-continuar');
  ok('Etapa 3', (await etapa()) === 3 && (await visivel('texto')));
  await w.fill('#texto', 'Primeira frase do teste. Segunda frase do teste.');
  await w.evaluate(() => document.getElementById('texto').dispatchEvent(new Event('change')));
  await w.keyboard.press('Alt+KeyV');
  await espera(300);
  ok('Alt V volta para a Etapa 2', (await etapa()) === 2);
  await w.click('#grav-nav-4');
  ok('navegação vai direto para a Etapa 4', (await etapa()) === 4);
  ok('na Etapa 4 com texto, o foco vai para a frase', (await foco()) === 'frase', await foco());
  ok('Etapa 4 só tem Gravar, Pausar, Enquadramento, Voltar, Fechar', await w.evaluate(() => [...document.querySelectorAll('#grav-e4 button')].filter((b) => b.offsetParent).map((b) => b.id).join() === 'gravar,pausar,enquadrar,grav-e4-voltar,grav-e4-fechar'));
  await w.keyboard.press('Alt+KeyR');
  ok('Alt R grava na Etapa 4', await ate(() => window.__gravador.gravador && window.__gravador.gravador.state === 'recording'));
  await w.keyboard.press('Alt+KeyP'); await espera(300);
  ok('Alt P pausa a gravação', await w.evaluate(() => window.__gravador.gravador.state === 'paused'));
  ok('o botão diz Alt P', /Alt P/.test(await w.textContent('#pausar')), await w.textContent('#pausar'));
  await w.keyboard.press('Alt+KeyP'); await espera(300);
  ok('Alt P retoma a gravação', await w.evaluate(() => window.__gravador.gravador.state === 'recording'));
  await w.keyboard.press('Alt+KeyT'); await espera(300);
  ok('Alt T continua pausando', await w.evaluate(() => window.__gravador.gravador.state === 'paused'));
  await w.keyboard.press('Alt+KeyT'); await espera(300);
  await w.click('#grav-nav-1');
  await espera(300);
  ok('gravando, não muda de etapa', (await etapa()) === 4 && /Pare a gravação/.test(await ultima()), await ultima());
  ok('gravando, Voltar e Fechar travados', await w.evaluate(() => document.getElementById('grav-e4-voltar').disabled && document.getElementById('grav-e4-fechar').disabled));
  await espera(2500);
  await w.keyboard.press('Alt+KeyR');
  ok('parou e foi para Tudo pronto', await ate(() => !document.getElementById('grav-decidir').hidden && !!window.__gravador.original, null, 120000));
  await w.click('#descartar');
  ok('descartar volta para a Etapa 4, foco em Gravar', await ate(() => !document.getElementById('grav-captura').hidden) && (await etapa()) === 4 && (await foco()) === 'gravar', await foco());
  for (const n of [4, 3, 2, 1]) await w.click(`#grav-e${n}-voltar`);
  ok('Voltar da Etapa 1 vai para a tela inicial', await ate(() => window.olho.telaAtual() === 'inicial', null, 5000));
  await w.evaluate(() => document.getElementById('ir-gravar').click());
  await ate(() => window.olho.telaAtual() === 'gravar');
  ok('ao entrar de novo, começa na Etapa 1 com as escolhas guardadas', (await etapa()) === 1 && await w.evaluate(() => !!document.querySelector('input[name="formato"]:checked')));
  ok('sem erros na página', erros.length === 0, erros.join(' | '));
  await app.close();
  console.log(falhas ? `${falhas} falha(s)` : 'tudo certo');
  process.exit(falhas ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(2); });
