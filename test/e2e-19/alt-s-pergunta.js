'use strict';
const { _electron } = require('playwright');
const fs = require('fs'), path = require('path'), os = require('os');
const RAIZ = process.argv[2], MIDIA = process.argv[3];
const espera = (ms) => new Promise((r) => setTimeout(r, ms));
let falhas = 0;
const ok = (n, c, x = '') => { console.log(`${c ? 'ok    ' : 'FALHOU'} ${n}${x !== '' ? ' — ' + String(x).slice(0, 300) : ''}`); if (!c) falhas++; };
(async () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'olho-ap-'));
  fs.copyFileSync(path.join(MIDIA, 'clipe.mp4'), path.join(tmp, 'clipe.mp4'));
  const app = await _electron.launch({ executablePath: require(path.join(RAIZ, 'node_modules', 'electron')), args: ['--no-sandbox', RAIZ], cwd: RAIZ,
    env: { ...process.env, OLHO_TESTE_DADOS: path.join(tmp, 'dados'), OLHO_TESTE_DOCUMENTOS: path.join(tmp, 'Documentos') } });
  const w = await app.firstWindow();
  const erros = []; w.on('pageerror', (e) => erros.push(e.message));
  await app.evaluate(({ dialog }, f) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [f] }); }, path.join(tmp, 'clipe.mp4'));
  const ate = async (f, arg, ms = 30000) => { const t0 = Date.now(); while (Date.now() - t0 < ms) { if (await w.evaluate(f, arg)) return true; await espera(150); } return false; };
  const clicar = async (id) => { await ate((i) => { const e = document.getElementById(i); return e && !e.disabled && e.offsetParent !== null; }, id); await w.click('#' + id); };
  const pv = path.join(tmp, 'Documentos', 'Olho da Cena');
  const arq = () => (fs.existsSync(pv) ? fs.readdirSync(pv).sort() : []);
  await ate(() => window.gravarTela && window.olho); await espera(800);
  await clicar('ir-config');
  ok('Configurações: Ao apertar Alt S', await w.evaluate(() => document.getElementById('cf-altSPergunta-automatico').checked && !!document.getElementById('cf-altSPergunta-perguntar')));
  await w.check('#cf-altSPergunta-perguntar');
  await ate(() => (window.__olhoConfig || {}).altSPergunta === 'perguntar', null, 5000);
  await w.keyboard.press('Alt+KeyV');
  await clicar('ir-cortar'); await clicar('ed-adicionar'); await ate(() => !document.getElementById('ed-opcoes').hidden);
  await w.keyboard.press('Alt+KeyS');
  ok('Editar: Alt S pergunta', await ate(() => document.getElementById('altS-dlg').open, null, 5000));
  await w.check('#altS-saida-audio'); await clicar('altS-dlg-salvar');
  ok('Apenas áudio: só o MP3', await ate((p) => true, null, 100) && await (async () => { const t0 = Date.now(); while (Date.now() - t0 < 30000) { const a = arq(); if (a.length) return a.join() === 'clipe - salvo.mp3'; await espera(300); } return false; })(), arq().join());
  await clicar('ed-audio');
  await ate(() => window.olho.telaAtual() === 'audio' && window.__audioCortes.video && !window.__audioCortes.salvando && /clipe/.test(document.getElementById('au-info').textContent));
  await ate(() => document.getElementById('au-player').readyState >= 1);
  await w.evaluate(() => { document.getElementById('au-player').currentTime = 1; }); await espera(300); await clicar('au-inicio');
  await w.evaluate(() => { document.getElementById('au-player').currentTime = 3; }); await espera(300); await clicar('au-fim');
  await w.keyboard.press('Alt+KeyS');
  ok('Cortes: Alt S pergunta', await ate(() => document.getElementById('altS-dlg').open, null, 5000));
  await clicar('altS-dlg-cancelar');
  ok('Cancelar: nada salvo', await ate(() => /Nada foi salvo/.test(document.getElementById('status').textContent), null, 3000) && arq().length === 1, arq().join());
  await w.keyboard.press('Alt+KeyS'); await ate(() => document.getElementById('altS-dlg').open, null, 5000);
  await w.check('#altS-saida-video'); await clicar('altS-dlg-salvar');
  const aoLado = () => fs.readdirSync(tmp);
  ok('Apenas vídeo: só o MP4 do trecho, ao lado do original', await (async () => { const t0 = Date.now(); while (Date.now() - t0 < 30000) { if (aoLado().some((f) => /trecho 1\.mp4$/.test(f))) return !aoLado().some((f) => /trecho 1\.mp3$/.test(f)) && !arq().some((f) => /trecho/.test(f)); await espera(300); } return false; })(), aoLado().join());
  ok('sem erros na página', erros.length === 0, erros.join(' | '));
  await app.close();
  console.log(falhas ? `${falhas} falha(s)` : 'tudo certo'); process.exit(falhas ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(2); });
